string markov_viterbi_segmentation(string text) {

    text.erase(remove_if(text.begin(), text.end(), ::isspace), text.end());
    int n = text.length();
    vector<double> viterbi_trellis(n + 1, -1e9);
    vector<int> backpointers(n + 1, 0);
    viterbi_trellis[0] = 0.0;
    
    for (int i = 1; i <= n; ++i) {
        double best_path_score = -1e9;
        int best_prev_state = 0;
        
        for (int k = max(0, i - 20); k < i; ++k) {
            string candidate_word = text.substr(k, i - k);
            double emission_prob = 0.0;
            if (VOCAB_SET.count(candidate_word)) emission_prob = pow(candidate_word.length(), 3) * 12.0; 
            else emission_prob = -(candidate_word.length() + 3.0);
            
            double transition_prob = 0.0;
            if (k > 0) {
                int prev_word_len = k - backpointers[k];
                if (candidate_word.length() == 1 && prev_word_len == 1) transition_prob = -15.0; 
                else if (candidate_word.length() > 3 && prev_word_len > 3) transition_prob = +2.0;
            }

            double current_score = viterbi_trellis[k] + emission_prob + transition_prob;
            if (current_score > best_path_score) {
                best_path_score = current_score;
                best_prev_state = k;
            }
        }
        viterbi_trellis[i] = best_path_score;
        backpointers[i] = best_prev_state;
    }
    
    vector<string> segmented_words;
    int curr_node = n;
    while (curr_node > 0) {
        int prev_node = backpointers[curr_node];
        segmented_words.push_back(text.substr(prev_node, curr_node - prev_node));
        curr_node = prev_node;
    }
    
    reverse(segmented_words.begin(), segmented_words.end());
    string reconstructed_plaintext = "";
    for (size_t i = 0; i < segmented_words.size(); ++i) {
        reconstructed_plaintext += segmented_words[i];
        if (i != segmented_words.size() - 1) reconstructed_plaintext += " ";
    }
    return reconstructed_plaintext;
}

