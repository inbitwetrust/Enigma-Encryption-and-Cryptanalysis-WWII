std::atomic<long long> global_attempts(0);
std::mutex results_mutex;

void bombe_worker(long long start_idx, long long end_idx, const string& ciphertext, const string& crib, const vector<vector<string>>& all_rotors, const vector<int>& offsets, vector<BombeResult>& valid_results) {

    long long local_attempts = 0;
    
    int current_perm = -1;

    alignas(32) int r_wires_int[3][32] = {0};
    alignas(32) int r_wires_inv_int[3][32] = {0};
    alignas(32) bool r_notches_bool[3][32] = {false};
    alignas(32) int ref_b_int[32] = {0};

    for(int i=0; i<26; i++) ref_b_int[i] = REFLECTOR_B[i] - 'A';
    vector<array<char, 32>> perms_slice(crib.length()); 

    for (long long i = start_idx; i < end_idx; ++i) {
        local_attempts++;
        if (local_attempts >= 500) {  
            global_attempts.fetch_add(local_attempts, std::memory_order_relaxed);
            local_attempts = 0;
        }
        
        int perm_idx = i / 456976; 
        int ring_right = (i / 17576) % 26;
        int pos_idx = i % 17576;
        
        if (perm_idx != current_perm) {
            current_perm = perm_idx;
            memset(r_notches_bool, 0, sizeof(r_notches_bool));
            for (int r = 0; r < 3; ++r) {
                string w = ROTORS[all_rotors[perm_idx][r]].wiring;
                string inv = "                          ";
                for(int k=0; k<26; ++k) inv[w[k]-'A'] = 'A'+k;

                for (int k = 0; k < 26; ++k) {
                    r_wires_int[r][k] = w[k] - 'A';
                    r_wires_inv_int[r][k] = inv[k] - 'A';
                }
                for (char n : ROTORS[all_rotors[perm_idx][r]].notch) {
                    r_notches_bool[r][n - 'A'] = true;
                }
            }
        }

        int p_int[3] = { (int)((pos_idx / 676) % 26), (int)((pos_idx / 26) % 26), (int)(pos_idx % 26) };

        for (size_t k = 0; k < crib.length(); ++k) {

            bool step_middle = r_notches_bool[1][p_int[1]];
            bool step_right  = r_notches_bool[2][p_int[2]];

            if (step_middle) {
                p_int[0] = (p_int[0] + 1) % 26;
                p_int[1] = (p_int[1] + 1) % 26;
            } else if (step_right) {
                p_int[1] = (p_int[1] + 1) % 26;
            }
            p_int[2] = (p_int[2] + 1) % 26;

            int core[3] = { p_int[0], p_int[1], (p_int[2] - ring_right + 26) % 26 };
            
            for (int c = 0; c < 26; ++c) {
                int c_idx = c;
                for (int r_idx = 2; r_idx >= 0; --r_idx) {
                    int shift = core[r_idx];
                    c_idx = (r_wires_int[r_idx][(c_idx + shift + 26) % 26] - shift + 52) % 26;
                }
                c_idx = ref_b_int[c_idx];
                for (int r_idx = 0; r_idx < 3; ++r_idx) {
                    int shift = core[r_idx];
                    c_idx = (r_wires_inv_int[r_idx][(c_idx + shift + 26) % 26] - shift + 52) % 26;
                }
                perms_slice[k][c] = (char)('A' + c_idx);
            }
        }
        
        for (int offset : offsets) {
            FastMap S;
            if (simulate_electrical_bombe_circuit(crib, ciphertext, offset, perms_slice, S)) {
                std::lock_guard<std::mutex> lock(results_mutex);
                if (valid_results.size() > 25000) continue;
                
                BombeResult res;
                res.position = string(1, 'A' + (pos_idx / 676) % 26) + string(1, 'A' + (pos_idx / 26) % 26) + string(1, 'A' + (pos_idx % 26));
                res.ring = "AA";
                res.ring += (char)('A' + ring_right);
                res.offset = offset;
                res.stecker = S.to_unordered();
                res.rotors = all_rotors[perm_idx];
                valid_results.push_back(res);
            }
        }
    }
    if (local_attempts > 0) global_attempts.fetch_add(local_attempts, std::memory_order_relaxed);
}

vector<BombeResult> brute_force_bombe(const string& ciphertext, const string& crib, const vector<vector<string>>& all_rotors, bool cillie_found) {

    vector<BombeResult> valid_results;
    vector<int> offsets;

    if (cillie_found) {
        offsets.push_back(0);
        cout << "\n[ " << get_timestamp() << " ] [FIXED-OFFSET MODE] Evaluating the selected crib only at Offset 0.\n";
    } else {
        offsets = find_and_sort_best_crib_offsets(ciphertext, crib);
    }

    if (offsets.empty()) {
        cout << "[-] No admissible alignment exists for this crib under the Enigma no-self-encryption constraint.\n";
        return valid_results;
    }

    unsigned int num_threads = std::thread::hardware_concurrency();

    if (num_threads == 0) num_threads = 4; 
    
    long long total_states = 60LL * 17576LL * 26LL;
    long long chunk_size = total_states / num_threads;

    if(chunk_size == 0) chunk_size = 1;
    
    cout << "[ " << get_timestamp() << " ] [*] STARTING NATIVE MULTITHREADED BOMBE-INSPIRED CONSTRAINT SEARCH...\n";
    cout << "      [*] Core state space: 60 rotor orders x 26 right-rotor ring settings x 17,576 start positions = 27,418,560 states.\n";
    cout << "      [*] Launching " << num_threads << " worker threads with precomputed rotor mappings and thread-local buffers.\n";
    cout << "      [*] Crib offsets evaluated per core state: " << offsets.size() << ".\n";
    
    auto start_time = chrono::high_resolution_clock::now();
    vector<std::thread> workers;
    global_attempts = 0;

    for (unsigned int i = 0; i < num_threads; ++i) {
        long long start_idx = i * chunk_size;
        long long end_idx = (i == num_threads - 1) ? total_states : start_idx + chunk_size;
        if(start_idx >= total_states) break;
        workers.push_back(std::thread(bombe_worker, start_idx, end_idx, std::ref(ciphertext), std::ref(crib), std::ref(all_rotors), std::ref(offsets), std::ref(valid_results)));
    }

    while (global_attempts.load() < total_states) {
        long long current_attempts = global_attempts.load();
        float progress = (float)current_attempts / total_states;
        int bar_len = 30;
        int filled = progress * bar_len;
        string bar = string(filled, '#') + string(bar_len - filled, '-');
        
        cout << "\r      [~] CORE-STATE SCAN: [" << bar << "] " 
             << (int)(progress * 100) << "% | States: " << current_attempts << " / " << total_states << flush;
             
        std::this_thread::sleep_for(std::chrono::milliseconds(50)); 
    }

    for (auto& t : workers) if (t.joinable()) t.join();

    auto end_time = chrono::high_resolution_clock::now();
    chrono::duration<double> elapsed = end_time - start_time;
    
    cout << "\r      [~] CORE-STATE SCAN: [" << string(30, '#') << "] 100% | States: " << total_states << " / " << total_states << flush;
    cout << "\n\n[ " << get_timestamp() << " ] [*] Bombe-inspired constraint sweep completed in " << elapsed.count() << " seconds.\n";
    if (!valid_results.empty()) cout << "      [*] Found " << valid_results.size() << " candidate configurations satisfying the current crib constraints.\n";
    return valid_results;
}

struct Phase15Result {

    BombeResult hit;
    float best_score;
    string best_ring;
    string best_pos;
};

void phase15_worker(int start_idx, int end_idx, const vector<BombeResult>& hits, const string& ciphertext, vector<Phase15Result>& results, atomic<int>& progress_counter) {

    for (int i = start_idx; i < end_idx; ++i) {
        auto hit = hits[i];
        float hit_best_score = -1e9f;
        string hit_best_ring = hit.ring;
        string hit_best_pos = hit.position;
        string full_ct = ciphertext; 

        int core_offset_left = (hit.position[0] - 'A'); 
        int core_offset_mid  = (hit.position[1] - 'A');

        for (int r0 = 0; r0 < 26; ++r0) {
            for (int r1 = 0; r1 < 26; ++r1) {
                
                string test_ring = "";
                test_ring += (char)('A' + r0);
                test_ring += (char)('A' + r1);
                test_ring += hit.ring[2];
                
                string test_start = "";
                test_start += (char)('A' + (core_offset_left + r0) % 26);
                test_start += (char)('A' + (core_offset_mid + r1) % 26);
                test_start += hit.position[2];
                
                string real_pos = test_start;
                
                if (hit.offset > 0) {

                    for(int j=0; j<17576; j++) {
                        string test_rewind = string(1, 'A' + j/676) + string(1, 'A' + (j/26)%26) + string(1, 'A' + j%26);
                        FastEnigmaCore fe(hit.rotors, test_ring, test_rewind);
                        for(int step=0; step<hit.offset; step++) fe.step();
                        if (fe.p[0] == test_start[0]-'A' && fe.p[1] == test_start[1]-'A' && fe.p[2] == test_start[2]-'A') {
                            real_pos = test_rewind; break;
                        }
                    }
                }
                
                string dec = apply_decryption(full_ct, hit.stecker, hit.rotors, test_ring, real_pos);
                float score = global_markov_engine.score_text(dec);
                
                if (score > hit_best_score) {
                    hit_best_score = score;
                    hit_best_ring = test_ring;
                    hit_best_pos = real_pos;
                }
            }
        }
        
        Phase15Result res;
        res.hit = hit;
        res.best_score = hit_best_score;
        res.best_ring = hit_best_ring;
        res.best_pos = hit_best_pos;
        results[i] = res;
        progress_counter++;
    }
}

