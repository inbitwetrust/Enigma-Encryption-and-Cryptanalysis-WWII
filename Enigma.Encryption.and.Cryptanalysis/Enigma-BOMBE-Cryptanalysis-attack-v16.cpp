Chromosome mutate(Chromosome child, const unordered_map<char, char>& locked_S, mt19937& rng) {

    vector<char> available;
    for (char c : ALPHABET) {
        if (!locked_S.count(c)) available.push_back(c);
    }
    if (available.size() < 2) return child;

    int idx1 = rng() % available.size();
    int idx2 = rng() % available.size();
    while (idx1 == idx2) idx2 = rng() % available.size();
    
    char a = available[idx1];
    char b = available[idx2];
    char target_a = child.map.count(a) ? child.map.at(a) : a;
    char target_b = child.map.count(b) ? child.map.at(b) : b;
    
    child.map.erase(target_a); child.map.erase(a);
    child.map.erase(target_b); child.map.erase(b);
    
    if (a != b) { child.map[a] = b; child.map[b] = a; }
    return child;
}

