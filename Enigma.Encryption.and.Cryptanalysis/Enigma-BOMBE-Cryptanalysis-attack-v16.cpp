static void replace_all_bytes(string& text, const string& from, const string& to) {
    if (from.empty()) return;
    size_t pos = 0;
    while ((pos = text.find(from, pos)) != string::npos) {
        text.replace(pos, from.length(), to);
        pos += to.length();
    }
}

string normalize_german_dictionary_word(string word) {

    replace_all_bytes(word, "\xC3\x84", "AE");
    replace_all_bytes(word, "\xC3\xA4", "AE");
    replace_all_bytes(word, "\xC3\x96", "OE");
    replace_all_bytes(word, "\xC3\xB6", "OE");
    replace_all_bytes(word, "\xC3\x9C", "UE");
    replace_all_bytes(word, "\xC3\xBC", "UE");
    replace_all_bytes(word, "\xC3\x9F", "SS");
    replace_all_bytes(word, "\xE1\xBA\x9E", "SS");

    replace_all_bytes(word, "A\xCC\x88", "AE");
    replace_all_bytes(word, "a\xCC\x88", "AE");
    replace_all_bytes(word, "O\xCC\x88", "OE");
    replace_all_bytes(word, "o\xCC\x88", "OE");
    replace_all_bytes(word, "U\xCC\x88", "UE");
    replace_all_bytes(word, "u\xCC\x88", "UE");

    string clean;
    clean.reserve(word.length() + 4);

    for (unsigned char c : word) {
        if (c >= 'a' && c <= 'z') {
            clean.push_back(static_cast<char>(c - 'a' + 'A'));
        } else if (c >= 'A' && c <= 'Z') {
            clean.push_back(static_cast<char>(c));
        }
    }

    return clean;
}

vector<string> build_normalized_dictionary(const vector<string>& source) {
    vector<string> normalized;
    normalized.reserve(source.size());

    unordered_set<string> seen;
    seen.reserve(source.size());

    for (const string& raw_word : source) {
        string clean_word = normalize_german_dictionary_word(raw_word);
        if (!clean_word.empty() && seen.insert(clean_word).second) {
            normalized.push_back(clean_word);
        }
    }

    return normalized;
}

