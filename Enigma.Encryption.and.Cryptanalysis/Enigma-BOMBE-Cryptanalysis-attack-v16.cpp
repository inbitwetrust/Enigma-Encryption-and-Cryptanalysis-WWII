string get_timestamp() {

    auto now = chrono::system_clock::now();
    time_t now_c = chrono::system_clock::to_time_t(now);
    struct tm *parts = localtime(&now_c);
    char buf[30];
    strftime(buf, sizeof(buf), "%d-%m-%Y %H:%M", parts);
    return string(buf);
}

