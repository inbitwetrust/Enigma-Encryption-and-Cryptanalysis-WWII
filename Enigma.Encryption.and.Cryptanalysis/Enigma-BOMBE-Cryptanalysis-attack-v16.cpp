class MarkovChainEngine {

private:
    vector<bool> valid_bigram;
    vector<bool> valid_quadgram;

public:
    MarkovChainEngine() {
        valid_bigram.assign(676, false);
        valid_quadgram.assign(456976, false);
        
        for (const string& clean_word : NORMALIZED_WEHRMACHT_DICT) {
            if (clean_word.length() < 2) continue;

            for(size_t i = 0; i < clean_word.length() - 1; ++i) {
                valid_bigram[(clean_word[i]-'A')*26 + (clean_word[i+1]-'A')] = true;
            }
            if(clean_word.length() >= 4) {
                for(size_t i = 0; i <= clean_word.length() - 4; ++i) {
                    string qg = clean_word.substr(i, 4);
                    int index = (qg[0]-'A')*17576 + (qg[1]-'A')*676 + (qg[2]-'A')*26 + (qg[3]-'A');
                    valid_quadgram[index] = true;
                }
            }
        }
    }
    float score_text(const string& text) {
        if (text.length() < 4) return 0.0f;
        
        int counts[26] = {0};
        for (char c : text) counts[c - 'A']++;
        
        float ioc = 0.0f;
        int n = text.length();
        for (int i = 0; i < 26; ++i) {
            ioc += (float)counts[i] * (counts[i] - 1);
        }
        ioc /= (float)(n * (n - 1));

        if (ioc > 0.095f) return -5000.0f; 
        if (ioc < 0.035f) return -5000.0f;

        float total_score = 0.0f;
        uint8_t bigram_cap[676] = {0};

        for (size_t i = 0; i < text.length() - 1; ++i) {
            int bi_idx = (text[i] - 'A') * 26 + (text[i+1] - 'A');
            if (valid_bigram[bi_idx]) {
                if (bigram_cap[bi_idx] < 6) {
                    total_score += 2.0f;
                    bigram_cap[bi_idx]++;
                }
            }
            if (i < text.length() - 3) {
                int c1 = text[i] - 'A';
                int c2 = text[i+1] - 'A';
                int c3 = text[i+2] - 'A';
                int c4 = text[i+3] - 'A';
                int quad_idx = c1 * 17576 + c2 * 676 + c3 * 26 + c4;
                if (valid_quadgram[quad_idx]) total_score += 15.0f; 
            }
        }
        return total_score + (ioc * 1000.0f);
    }
};

