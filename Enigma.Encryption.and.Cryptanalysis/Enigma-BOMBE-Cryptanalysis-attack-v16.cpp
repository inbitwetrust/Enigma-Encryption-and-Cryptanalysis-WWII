class FastEnigmaCore {

public:
    vector<string> r;
    vector<string> n;
    vector<int> rings;
    vector<int> p_init;
    vector<int> p;
    string ref;

    FastEnigmaCore(const vector<string>& rotor_names, const string& rings_str, const string& pos_str) {
        for (const auto& name : rotor_names) {
            r.push_back(ROTORS[name].wiring);
            n.push_back(ROTORS[name].notch);
        }
        for (char c : rings_str) rings.push_back(ALPHABET.find(c));
        for (char c : pos_str) p_init.push_back(ALPHABET.find(c));
        p = p_init;
        ref = REFLECTOR_B;
    }

    void step() {
        bool step_middle = n[1].find(ALPHABET[p[1]]) != string::npos;
        bool step_right = n[2].find(ALPHABET[p[2]]) != string::npos;

        if (step_middle) {
            p[0] = (p[0] + 1) % 26;
            p[1] = (p[1] + 1) % 26;
        } else if (step_right) {
            p[1] = (p[1] + 1) % 26;
        }
        p[2] = (p[2] + 1) % 26;
    }
};

string apply_decryption(const string& ciphertext, const unordered_map<char, char>& S_dict, const vector<string>& rotors, const string& rings, const string& pos) {

    FastEnigmaCore enigma(rotors, rings, pos);
    string out = "";

    for (char char_in : ciphertext) {
        enigma.step();
        char mapped = S_dict.count(char_in) ? S_dict.at(char_in) : char_in;
        int c_idx = ALPHABET.find(mapped);
        
        for (int i = 2; i >= 0; --i) {
            int shift = enigma.p[i] - enigma.rings[i];
            int access = (c_idx + shift) % 26;
            if (access < 0) access += 26;
            c_idx = ((int)ALPHABET.find(enigma.r[i][access]) - shift) % 26;
            if (c_idx < 0) c_idx += 26;
        }
        c_idx = ALPHABET.find(enigma.ref[c_idx]);
        for (int i = 0; i < 3; ++i) {
            int shift = enigma.p[i] - enigma.rings[i];
            int access = (c_idx + shift) % 26;
            if (access < 0) access += 26;
            c_idx = ((int)enigma.r[i].find(ALPHABET[access]) - shift) % 26;
            if (c_idx < 0) c_idx += 26;
        }
        char out_char = ALPHABET[c_idx];
        out += S_dict.count(out_char) ? S_dict.at(out_char) : out_char;
    }
    return out;
}

